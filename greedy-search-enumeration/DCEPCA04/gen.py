def count_ways(counts, chosen, threshold):
    stride = chosen * 100 + 1
    poly = 1
    for amount in counts:
        poly = poly + (poly << ((stride + amount) * 40))
    return sum((poly >> ((chosen * stride + score) * 40)) & MASK
               for score in range(threshold, chosen * 100 + 1))


def oracle(text):
    tokens = [int(token) for token in text.split()]
