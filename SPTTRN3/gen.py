def is_star(row, col, size):
    group = 0
    while True:
        top = 2 * group
        end = size - 1 - 2 * group
        if top > end:
            return False
        reach = end - top
        if group % 2 == 0:
            if row == top and top <= col <= end:
                return True
            if col == end and top <= row <= end:
                return True
            if reach >= 2 and row == end and top <= col <= end:
                return True
            if reach >= 3 and col == top and top + 2 <= row <= end:
                return True
            if reach >= 4 and row == top + 2 and top <= col <= top + 2:
                return True
        else:
            if col == top and top <= row <= end:
                return True
            if reach >= 2 and col == end and top <= row <= end:
                return True
            if row == end and top <= col <= end:
                return True
            if reach >= 3 and row == top and top + 2 <= col <= end:
                return True
            if reach >= 4 and col == top + 2 and top <= row <= top + 2:
                return True
        group += 1


def oracle(sizes):
    blocks = []
    for size in sizes:
        rows = []
        for row in range(size):
            line = ""
            for col in range(size):
                if is_star(row, col, size):
                    line += "*"
                else:
                    line += "."
            rows.append(line)
        blocks.append("\n".join(rows) + "\n\n")
    return "".join(blocks)


