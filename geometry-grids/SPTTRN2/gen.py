ROOT = Path(__file__).resolve().parent


def arm_lengths(size):
    base = size - 1
    lengths = [base, base, base]
    step = base - 2
    while step > 0:
        if step == 1:
            lengths.append(1)
            break
        lengths.extend([step, step])
        step -= 2
    return lengths


COUNTER_ROWS = [1, 0, -1, 0]
COUNTER_COLS = [0, 1, 0, -1]


def oracle(sizes):
    blocks = []
    for size in sizes:
        grid = [['.'] * size for _ in range(size)]
        row, col = 0, 0
        grid[row][col] = '*'
        for arm_index, steps in enumerate(arm_lengths(size)):
            row_step = COUNTER_ROWS[arm_index % 4]
            col_step = COUNTER_COLS[arm_index % 4]
            for _ in range(steps):
                next_row = row + row_step
                next_col = col + col_step
                if not (0 <= next_row < size and 0 <= next_col < size):
                    break
                row, col = next_row, next_col
                grid[row][col] = '*'
        blocks.append('\n'.join(''.join(line) for line in grid) + '\n\n')
    return ''.join(blocks)


